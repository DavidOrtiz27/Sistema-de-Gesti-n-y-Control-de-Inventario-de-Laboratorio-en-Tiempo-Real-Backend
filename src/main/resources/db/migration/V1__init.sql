CREATE EXTENSION IF NOT EXISTS btree_gist;

create table roles
(
    id         bigint generated by default as identity primary key,
    name       varchar(100) unique not null,
    created_at timestamptz         not null,
    updated_at timestamptz         not null
);

create table careers
(
    id         bigint generated by default as identity primary key,
    name       varchar(100) unique not null,
    is_active  boolean             not null default true,
    created_at timestamptz         not null,
    updated_at timestamptz         not null
);

create table users
(
    id                bigint generated by default as identity primary key,
    role_id           bigint              not null,
    career_id         bigint,
    first_name        varchar(100)        not null,
    last_name         varchar(100)        not null,
    identity_document varchar(100) unique not null,
    phone_number      varchar(30),
    email             varchar(100)        not null,
    password_hash     varchar(200)        not null,
    is_active         boolean             not null default true,
    created_at        timestamptz         not null,
    updated_at        timestamptz         not null,

    constraint fk_users_role
        foreign key (role_id)
            references roles (id),

    constraint fk_users_career
        foreign key (career_id)
            references careers (id)
);

create unique index idx_users_email_lower on users (lower(email));

create table categories
(
    id         bigint generated by default as identity primary key,
    name       varchar(100) unique not null,
    is_active  boolean             not null default true,
    created_at timestamptz         not null,
    updated_at timestamptz         not null
);

create table equipment_types
(
    id          bigint generated by default as identity primary key,
    category_id bigint       not null,
    name        varchar(100) not null,
    brand       varchar(100),
    model       varchar(100),
    is_active   boolean      not null default true,
    created_at  timestamptz  not null,
    updated_at  timestamptz  not null,

    constraint fk_equipment_types_category
        foreign key (category_id)
            references categories (id)
);

create table equipment_items
(
    id                 bigint generated by default as identity primary key,
    equipment_type_id  bigint              not null,
    internal_code      varchar(100) unique not null,
    serial_number      varchar(100) unique,
    shelf              varchar(50),
    rack               varchar(50),
    physical_condition varchar(20)         not null,
    status             varchar(20)         not null,
    comments           text,
    created_at         timestamptz         not null,
    updated_at         timestamptz         not null,

    constraint chk_equipment_items_condition
        check (physical_condition in ('EXCELLENT', 'GOOD', 'FAIR', 'POOR')),

    constraint chk_equipment_items_status
        check (status in ('AVAILABLE', 'ON_LOAN', 'IN_REPAIR', 'RETIRED')),

    constraint fk_equipment_items_equipment_type
        foreign key (equipment_type_id)
            references equipment_types (id)
);

create table bookings
(
    id                   bigint generated by default as identity primary key,
    user_id              bigint      not null,
    equipment_type_id    bigint      not null,
    quantity             int         not null,
    start_date           date        not null,
    end_date             date        not null,
    status               varchar(20) not null,
    rejection_reason     text,
    cancelled_by_user_id bigint,
    created_at           timestamptz not null,
    updated_at           timestamptz not null,

    constraint chk_bookings_quantity
        check (quantity > 0),

    constraint chk_bookings_dates
        check (end_date > start_date),

    constraint chk_bookings_status
        check (status in ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),

    constraint fk_bookings_user
        foreign key (user_id)
            references users (id),

    constraint fk_bookings_equipment_type
        foreign key (equipment_type_id)
            references equipment_types (id),

    constraint fk_bookings_cancelled_by_user
        foreign key (cancelled_by_user_id)
            references users (id)
);

create table loans
(
    id                    bigint generated by default as identity primary key,
    booking_id            bigint,
    equipment_item_id     bigint      not null,
    borrower_user_id      bigint      not null,
    registered_by_user_id bigint      not null,
    received_by_user_id   bigint,
    loan_date             date        not null,
    expected_return_date  date        not null,
    actual_return_date    date,
    status                varchar(20) not null,
    initial_condition     varchar(20) not null,
    return_condition      varchar(20),
    dispatch_notes        text,
    return_notes          text,
    created_at            timestamptz not null,
    updated_at            timestamptz not null,

    constraint chk_loans_dates
        check (expected_return_date > loan_date),

    constraint chk_loans_status
        check (status in ('ACTIVE', 'RETURNED', 'OVERDUE', 'LOST')),

    constraint chk_loans_initial_condition
        check (initial_condition in ('EXCELLENT', 'GOOD', 'FAIR', 'POOR')),

    constraint chk_loans_return_condition
        check (return_condition in ('EXCELLENT', 'GOOD', 'FAIR', 'POOR')),

    constraint excl_loans_item_overlap
        exclude using gist (
            equipment_item_id with =,
            daterange(loan_date, expected_return_date, '[)') with &&
        ) where (status in ('ACTIVE', 'OVERDUE')),

    constraint fk_loans_booking
        foreign key (booking_id)
            references bookings (id),

    constraint fk_loans_equipment_item
        foreign key (equipment_item_id)
            references equipment_items (id),

    constraint fk_loans_borrower_user
        foreign key (borrower_user_id)
            references users (id),

    constraint fk_loans_registered_by_user
        foreign key (registered_by_user_id)
            references users (id),

    constraint fk_loans_received_by_user
        foreign key (received_by_user_id)
            references users (id)
);
